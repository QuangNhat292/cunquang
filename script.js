function getEvenHeartPoints(count) {
  const sampleCount = 1800;
  const rawPoints = Array.from({ length: sampleCount + 1 }, (_, index) => {
    const t = (Math.PI * 2 * index) / sampleCount;
    return {
      x: 16 * Math.pow(Math.sin(t), 3),
      y: -(
        13 * Math.cos(t) -
        5 * Math.cos(2 * t) -
        2 * Math.cos(3 * t) -
        Math.cos(4 * t)
      ),
    };
  });
  const minX = Math.min(...rawPoints.map((point) => point.x));
  const maxX = Math.max(...rawPoints.map((point) => point.x));
  const minY = Math.min(...rawPoints.map((point) => point.y));
  const maxY = Math.max(...rawPoints.map((point) => point.y));
  const points = rawPoints.map((point) => ({
    x: 11 + ((point.x - minX) / (maxX - minX)) * 78,
    y: 8 + ((point.y - minY) / (maxY - minY)) * 82,
  }));
  const distances = [0];

  for (let index = 1; index < points.length; index++) {
    const previous = points[index - 1];
    const current = points[index];
    distances[index] =
      distances[index - 1] +
      Math.hypot((current.x - previous.x) * 1.18, current.y - previous.y);
  }

  const totalLength = distances[distances.length - 1];
  return Array.from({ length: count }, (_, index) => {
    const targetDistance = (totalLength * index) / count;
    const segment = distances.findIndex(
      (distance) => distance >= targetDistance,
    );
    const previousIndex = Math.max(0, segment - 1);
    const segmentLength = distances[segment] - distances[previousIndex] || 1;
    const progress =
      (targetDistance - distances[previousIndex]) / segmentLength;
    const start = points[previousIndex];
    const end = points[segment];
    return {
      x: start.x + (end.x - start.x) * progress,
      y: start.y + (end.y - start.y) * progress,
    };
  });
}

