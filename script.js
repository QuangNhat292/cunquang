function clearAllActiveTyping() {
  if (currentTypingTimeout) {
    clearTimeout(currentTypingTimeout);
    currentTypingTimeout = null;
  }

  currentTypingTargets.forEach((target) => {
    if (target.isRunning) {
      target.element.innerHTML = target.fullText;
      target.isRunning = false;
    }
  });
  currentTypingTargets = [];
}

function typewritePage(faceIndex, callback) {
  const element = document.getElementById(`text-face-${faceIndex}`);
  if (!element) {
    if (callback) callback();
    return;
  }

  const text = element.getAttribute("data-text");
  if (!text) {
    if (callback) callback();
    return;
  }

  if (typedPages.has(faceIndex)) {
    element.innerHTML = text.replace(/\n/g, "<br>");
    if (callback) callback();
    return;
  }

  element.innerHTML = "";

  const target = {
    element: element,
    fullText: text,
    isRunning: true,
  };
  currentTypingTargets.push(target);

  let charIndex = 0;

  function typeNextChar() {
    if (!target.isRunning) return;

    if (charIndex >= text.length) {
      target.isRunning = false;
      typedPages.add(faceIndex);
      if (callback) callback();
      return;
    }
    if (text.substring(charIndex, charIndex + 4).toLowerCase() === "<br>") {
      element.innerHTML += "<br>";
      charIndex += 4;
    } else {
      const char = text.charAt(charIndex);
      if (char === "\n") {
        element.innerHTML += "<br>";
      } else {
        element.innerHTML += char;
      }
      charIndex++;
    }

    element.scrollTop = element.scrollHeight;

    currentTypingTimeout = setTimeout(typeNextChar, 18);
  }

  typeNextChar();
}

function triggerSpreadTyping(S) {
  clearAllActiveTyping();

  const restartBtn = document.getElementById("btn-restart");
  if (restartBtn) {
    restartBtn.classList.remove("visible");
  }

  typewritePage(S, () => {
    if (S === finalSpread) {
      if (restartBtn) {
        restartBtn.classList.add("visible");
      }
    }
  });
}

function completeCurrentTyping() {
  let completedAny = false;
  currentTypingTargets.forEach((target) => {
    if (target.isRunning) {
      target.element.innerHTML = target.fullText.replace(/\n/g, "<br>");
      target.isRunning = false;
      completedAny = true;

      const match = target.element.id.match(/text-face-(\d+)/);
      if (match) {
        typedPages.add(parseInt(match[1], 10));
      }
    }
  });

  if (currentTypingTimeout) {
    clearTimeout(currentTypingTimeout);
    currentTypingTimeout = null;
  }

  if (completedAny) {
    const rightEl = document.getElementById(`text-face-${currentSpread}`);
    if (rightEl) {
      rightEl.innerHTML = rightEl
        .getAttribute("data-text")
        .replace(/\n/g, "<br>");
      typedPages.add(currentSpread);
    }

    currentTypingTargets.forEach((target) => {
      target.isRunning = false;
    });

    if (currentSpread === finalSpread) {
      const restartBtn = document.getElementById("btn-restart");
      if (restartBtn) {
        restartBtn.classList.add("visible");
      }
    }
    return true;
  }
  return false;
}

function isClickOnScrollbar(e, el) {
  const rect = el.getBoundingClientRect();
  const clickX = e.clientX - rect.left;
  return clickX > el.clientWidth;
}

document.querySelectorAll(".text-content").forEach((el) => {
  el.addEventListener("click", (e) => {
    const isTypingActive = currentTypingTargets.some(
      (target) => target.element === el && target.isRunning,
    );
    if (isTypingActive) {
      return;
    }

    if (isClickOnScrollbar(e, el)) {
      e.stopPropagation();
      return;
    }
    if (window.getSelection().toString().length > 0) {
      e.stopPropagation();
      return;
    }
  });
});

